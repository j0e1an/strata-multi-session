"""Per-user auto-start: the systemd user unit, the LaunchAgent plist, and how to turn them on.

spec §11 asks for auto-start that needs no password on either OS this tool supports. That is a
*user* service on both: ``~/.config/systemd/user/strata.service`` enabled with ``systemctl
--user``, and ``~/Library/LaunchAgents/dev.strata.plist`` loaded with ``launchctl``. Nothing here
writes a file or runs a command — :func:`render` returns text and :func:`enable_commands` returns
the two command lines (enable, undo) — so the module is testable on a box with no systemd and
Task 7 alone decides whether anything gets run.

Why the unit looks the way it does, in the order the surprises were found
    **No browser flag at all.** Upstream's own launcher is ``[sys.executable, ROOT/"serve"/
    "server.py", "--engine", "strata", "--config", cfg, "--port", port]`` plus ``--open`` only
    when a browser is wanted (``setup.py:5388-5391``). Inside a unit ``--open`` means "launch a
    browser on a headless box", so it is left out — and ``--no-browser`` is *not* the substitute:
    that flag belongs to ``setup.py:5759``, while ``serve/server.py`` parses strictly
    (``serve/server.py:6669``, ``ap.parse_args()``) and knows only ``--open`` (``:6639``). Measured
    on this box 2026-10-18: ``server.py: error: unrecognized arguments: --no-browser``, exit 2.
    A unit that passed it would exit 2 on every start and ``Restart=on-failure`` would spin it.

    **Absolute paths in the body, ``~`` only in :func:`unit_path`.** systemd refuses a tilde in
    ``ExecStart`` ("Neither a valid executable name nor an absolute path ... Unit configuration
    has fatal error, unit will not be started" from ``systemd-analyze verify``) and launchd
    expands neither ``~`` nor ``$HOME``. Task 7's defaults are ``~/Strata-data`` paths, so
    :func:`render` expands every path argument it is given. :func:`unit_path` keeps the ``~`` form
    because it answers a different question — "where do I write this", for a human to read.

    **The port and the interpreter are arguments, not assumptions.** ``server.py`` defaults to
    8095 (``serve/server.py:6634``) and takes the port from the flag alone — ``:6678`` reads
    ``a.port``, and the ``"port"`` key this box's config carries is never read by ``server.py`` —
    so a unit that omits ``--port`` listens on 8095 while the install expects 18080. The default
    here is 8095 because that is ``server.py``'s own, and Task 7 passes the real one.
    ``python_bin`` exists because upstream's launcher uses ``sys.executable``: the venv is what
    holds the pinned dependencies. System ``python3`` happens to run ``server.py`` on this box,
    which is luck, not the design; ``detect.detect()`` returns ``venv_python`` for exactly this
    handoff.

    **The unit owns ``serve/server.py``, never a router.** spec §11: if a llama-swap is found the
    tool says so and leaves it alone rather than managing two things, and the unit does not exec
    upstream's per-model launcher. :func:`detect_llama_swap` is that report — a TCP probe, not a
    switch.

Two things the service managers, not this file, enforce: ``ExecStart`` is split by systemd's own
parser, so an argument with a space or a ``$`` has to be quoted the way systemd quotes (double
quotes, backslash escapes — not shell single quotes); and a plist launchd rejects is a plist that
never loads, so the macOS side is built with :mod:`plistlib` rather than by hand.
"""

import os
import plistlib
import socket

# spec §11's two locations. `~` on purpose: these are printed at a user as "where the file goes",
# while render() writes absolute paths into the file. UNIT_NAME is what `systemctl --user enable`
# and `journalctl --user -u` both call it.
UNIT_NAME = "strata.service"
PLIST_LABEL = "dev.strata"
UNIT_PATHS = {
    "linux": "~/.config/systemd/user/" + UNIT_NAME,
    "darwin": "~/Library/LaunchAgents/%s.plist" % PLIST_LABEL,
}

# server.py's own default (serve/server.py:6634), so the default here is honest rather than a
# second guess; Task 7 passes the port the install actually uses.
DEFAULT_PORT = 8095
DEFAULT_PYTHON = "python3"

# Where a llama-swap sits by default, and how long to wait for it. Loopback answers in
# milliseconds; anything slower than this is a box with worse problems than this probe.
LLAMA_SWAP_PORT = 8090
PROBE_TIMEOUT = 0.3

# The unit body. `append:` (not `file:`) so a restart does not truncate the previous crash, and
# stdout and stderr both go there so the one path Task 7 prints holds the whole story;
# `journalctl --user -u strata` still carries the exit status. PYTHONUNBUFFERED because a unit has
# no tty and Python would block-buffer the log for kilobytes at a time. WantedBy=default.target is
# the user-instance equivalent of multi-user.target — what `loginctl enable-linger` boots.
LINUX_UNIT = """# Generated by Strata's setup. Per-user unit: systemctl --user, never a system unit.
# The server runs directly with no browser flag, because a unit has no display. stdout and
# stderr both go to the log path below; `journalctl --user -u strata` shows the exit status.
[Unit]
Description=Strata inference server
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
ExecStart={exec_start}
WorkingDirectory={workdir}
Restart=on-failure
RestartSec=5
Environment=PYTHONUNBUFFERED=1
StandardOutput=append:{log}
StandardError=append:{log}

[Install]
WantedBy=default.target
"""


def _fail(os_name: str, what: str) -> None:
    """Raise for an OS this tool does not install for.

    ``detect.detect()`` returns only ``linux`` or ``darwin``, so reaching this is a programming
    error at the module boundary — returning a systemd unit for ``"windows"`` would be a silent
    wrong answer printed to a user.
    """
    raise ValueError("%s: unsupported os %r (this tool installs auto-start for %s)"
                     % (what, os_name, " and ".join(sorted(UNIT_PATHS))))


def _abs(path: str) -> str:
    """Absolute, with ``~`` gone — what both service managers need in a unit body.

    systemd calls a tilde in ``ExecStart`` a fatal error and launchd expands neither ``~`` nor
    ``$HOME``, while Task 7's defaults are ``~/Strata-data`` paths. A path still relative after
    expansion is resolved against the current directory: the alternative is a unit whose
    ``WorkingDirectory`` is empty, which is a worse answer than a guess made where the file is
    being written.

    One exception, and it is the interpreter: a bare name with no separator (``python3``) is left
    alone, because that is a program for the manager to find on ``$PATH``, not a path to resolve.
    Making it absolute against the cwd is the bug this branch exists to avoid — ``systemd-analyze
    verify`` answers "Command <cwd>/python3 is not executable", measured on this box 2026-10-18.
    """
    expanded = os.path.expanduser(path)
    if os.path.isabs(expanded) or (expanded and "/" not in expanded and not expanded.startswith("~")):
        return expanded
    return os.path.abspath(expanded)


def _root(server: str) -> str:
    """The install root a Strata ``server.py`` sits under — ``ROOT/serve/server.py``.

    Three places name the same directory, one level above ``serve/``: ``serve/server.py:57``
    computes its own ``ROOT`` as ``Path(__file__).resolve().parents[1]``, upstream's launcher
    writes ``cd "<ROOT>"`` (``setup.py:5398``), and this box's config carries
    ``"cwd": "/home/joe/Strata"`` (``strata-iq3_s-abliterated.json:40``). It is not cosmetic:
    ``serve/server.py:6736`` resolves a relative ``"exe"`` against ``cfg.get("cwd") or "."``, so
    for a config written without that key the process cwd is the directory the engine's paths
    come out of — and ``serve/`` is the wrong answer by one level.
    """
    return os.path.dirname(os.path.dirname(server)) or os.sep


def _systemd_quote(arg: str) -> str:
    """Quote one ``ExecStart`` argument the way systemd's own parser wants it.

    Not shell quoting: systemd splits ``ExecStart`` itself, treats single quotes as literal
    characters, and expands ``$NAME`` inside double quotes — so ``$``, backtick, backslash and
    ``"`` get backslash-escaped and the whole argument goes in double quotes when it holds
    anything systemd would split or expand.
    """
    if arg and not any(c.isspace() or c in "$`\"\\" for c in arg):
        return arg
    escaped = "".join("\\" + c if c in "$`\"\\" else c for c in arg)
    return '"%s"' % escaped


def unit_path(os_name: str) -> str:
    """Where the auto-start file goes, in ``~`` form, for a human to read (spec §11)."""
    if os_name not in UNIT_PATHS:
        _fail(os_name, "unit_path")
    return UNIT_PATHS[os_name]


def render(os_name: str, server_py: str, config: str, log: str, *, port: int = DEFAULT_PORT,
           python_bin: str = DEFAULT_PYTHON) -> str:
    """The unit (Linux) or plist (macOS) that starts Strata, as text. Writes nothing.

    ``server_py``/``config``/``log`` may be ``~`` paths — they come from Task 7's ``~/Strata-data``
    defaults — and are expanded here, because the file itself must hold absolute paths.
    ``WorkingDirectory`` is the server's own root, which is what upstream's launcher ``cd`` s into
    (``setup.py:5398``) and what ``server.py`` resolves its tokenizer and pack paths against.
    ``port`` and ``python_bin`` are keyword-only with honest defaults so the four positional
    arguments stay the whole call for a caller that has nothing to say about either.
    """
    if os_name not in UNIT_PATHS:
        _fail(os_name, "render")
    server, cfg, logfile, interp = (_abs(p) for p in (server_py, config, log, python_bin))
    argv = [interp, server, "--engine", "strata", "--config", cfg, "--port", str(port)]
    workdir = _root(server)

    if os_name == "darwin":
        # launchd takes an argv list, so no quoting question arises; RunAtLoad starts it now and
        # KeepAlive restarts it when it dies, which together are the macOS half of `Restart=`.
        payload = {
            "Label": PLIST_LABEL,
            "ProgramArguments": argv,
            "WorkingDirectory": workdir,
            "RunAtLoad": True,
            "KeepAlive": True,
            "EnvironmentVariables": {"PYTHONUNBUFFERED": "1"},
            "StandardOutPath": logfile,
            "StandardErrorPath": logfile,
        }
        return plistlib.dumps(payload, sort_keys=False).decode("utf-8")

    return LINUX_UNIT.format(
        exec_start=" ".join(_systemd_quote(a) for a in argv),
        workdir=workdir,
        log=logfile)


def enable_commands(os_name: str) -> tuple[str, str]:
    """``(enable, undo)`` — the two command lines to print, neither of which needs a password.

    Linux needs ``daemon-reload`` first: a unit file dropped into ``~/.config/systemd/user`` is
    invisible to the manager until it re-reads the directory. ``--now`` starts it as it enables it,
    and ``loginctl enable-linger $USER`` is the half that makes it come up with nobody logged in
    (spec §11); ``$USER`` is left for the shell to expand. The undo disables *both* halves — undoing
    only ``systemctl`` leaves linger on, so the unit keeps coming back at boot for a user who just
    asked it to stop.

    macOS has no linger to manage: ``load -w`` is what makes the LaunchAgent load at next login
    and now, and ``unload`` is its exact inverse. Both OSes leave the file in place, because
    undoing the enable is not the same act as deleting what Task 7 wrote.
    """
    if os_name not in UNIT_PATHS:
        _fail(os_name, "enable_commands")
    if os_name == "darwin":
        plist = UNIT_PATHS["darwin"]
        return ("launchctl load -w %s" % plist, "launchctl unload %s" % plist)
    return ("systemctl --user daemon-reload && systemctl --user enable --now %s"
            " && loginctl enable-linger $USER" % UNIT_NAME,
            "systemctl --user disable --now %s && loginctl disable-linger $USER" % UNIT_NAME)


def detect_llama_swap(port: int = LLAMA_SWAP_PORT) -> bool:
    """Is *anything* listening on ``127.0.0.1:port`` — the router this box happens to have.

    A report, not a switch: spec §11 says the unit owns ``serve/server.py`` and a detected router
    is told to the user and left alone. The name is the promise about what the port usually holds;
    the answer is only "something is there", so the caller must not claim it identified llama-swap.

    Plain TCP connect, short timeout, every failure a ``False``. Out of range or non-numeric ports
    raise ``OverflowError``/``TypeError`` from the socket layer rather than ``OSError``, and this
    runs during an install where a config's bad port is a shrug, not a traceback.
    """
    try:
        with socket.create_connection(("127.0.0.1", port), timeout=PROBE_TIMEOUT):
            return True
    except (OSError, OverflowError, TypeError, ValueError):
        return False
